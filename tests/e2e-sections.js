const assert = require("node:assert/strict");
const { openTestApp } = require("./e2e-helper");

(async () => {
  const { browser, page, errors } = await openTestApp();
  try {
    await page.evaluate(async () => {
      const list = createList({ id: "sections-list", title: "Робота", kind: "regular", position: 0 });
      const task = createTask({ id: "sections-task", title: "Завдання", listId: list.id });
      await listDb.put(list);
      await taskDb.put(task);
    });
    await page.reload({ waitUntil: "networkidle" });
    await page.evaluate(() => openList("sections-list"));
    await page.locator("#list-editor-open").click();
    await page.locator("#section-create-name").fill("План");
    await page.locator("#section-create-form button").click();
    await page.locator("#list-sections li").first().waitFor();
    await page.locator("#section-create-name").fill("Виконання");
    await page.locator("#section-create-form button").click();
    assert.deepEqual(await page.locator("#list-sections .section-name").evaluateAll(nodes => nodes.map(node => node.value)), ["План", "Виконання"]);
    await page.locator("#list-sections li").nth(1).locator('[data-action="up"]').click();
    assert.deepEqual(await page.locator("#list-sections .section-name").evaluateAll(nodes => nodes.map(node => node.value)), ["Виконання", "План"]);
    await page.locator("#list-sections li").first().locator(".section-name").fill("Робити");
    await page.locator("#list-sections li").first().locator(".section-name").dispatchEvent("change");
    await page.locator("#list-editor-close").click();
    assert.equal(await page.locator(".task-section-select").count(), 0);
    await page.locator(".swipe-row[data-id='sections-task'] .task-open").click();
    await page.locator("#task-list-trigger").click();
    await page.locator("#task-list-options [data-list-id='sections-list']").click();
    await page.locator("#task-section-options").waitFor();
    await page.locator("#task-section-options [data-section-id]").filter({ hasText: "Робити" }).click();
    await page.locator("#task-editor-back").click();
    await page.locator(".list-section-heading").first().waitFor();
    assert.equal(await page.locator(".list-section").first().locator(".task-text").textContent(), "Завдання");
    await page.reload({ waitUntil: "networkidle" });
    await page.evaluate(() => openList("sections-list"));
    assert.equal(await page.locator(".list-section-label").first().textContent(), "Робити");
    assert.equal(await page.locator(".list-section").first().locator(".task-text").textContent(), "Завдання");
    await page.evaluate(() => openNewTaskEditor("sections-list"));
    await page.locator("#task-title").fill("Нове в секції");
    await page.locator("#task-list-trigger").click();
    await page.locator("#task-list-options [data-list-id='sections-list']").click();
    await page.locator("#task-section-options [data-section-id]").filter({ hasText: "Робити" }).click();
    await page.locator("#task-editor-back").click();
    await page.locator(".list-section").first().getByText("Нове в секції").waitFor();
    const firstSection = page.locator(".list-section").first();
    assert.equal(await firstSection.locator(".list-section-count").textContent(), "2");
    await firstSection.locator(".list-section-toggle").click();
    await page.locator(".list-section-tasks").first().waitFor({ state: "hidden" });
    await page.reload({ waitUntil: "networkidle" });
    await page.evaluate(() => openList("sections-list"));
    assert.equal(await page.locator(".list-section").first().locator(".list-section-toggle").getAttribute("aria-expanded"), "false");
    assert.equal(await page.locator(".list-section").first().locator(".list-section-count").textContent(), "2");
    await page.locator(".list-section").first().locator(".list-section-toggle").click();
    await page.locator(".list-section").first().getByText("Нове в секції").waitFor();
    await page.evaluate(() => openNewTaskEditor("system-list-inbox"));
    assert.equal(await page.locator("#task-section-row").isVisible(), false);
    await page.locator("#task-editor-back").click();
    await page.locator("#list-editor-open").click();
    page.once("dialog", dialog => dialog.dismiss());
    await page.locator("#list-sections li").first().locator('[data-action="delete"]').click();
    assert.equal(await page.locator("#list-sections li").count(), 2);
    page.once("dialog", dialog => dialog.accept());
    await page.locator("#list-sections li").first().locator('[data-action="delete"]').click();
    assert.equal(await page.locator("#list-sections li").count(), 1);
    const saved = await page.evaluate(async () => ({ sections: await sectionDb.all(), task: (await taskDb.all()).find(task => task.id === "sections-task") }));
    assert.equal(saved.task.listId, "sections-list");
    assert.equal(saved.task.sectionId, null);
    assert.equal((await page.evaluate(() => taskDb.all())).find(task => task.title === "Нове в секції").sectionId, null);
    assert.equal(saved.sections.length, 1);
    assert.deepEqual(errors, []);
    console.log("sections scenario passed");
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });

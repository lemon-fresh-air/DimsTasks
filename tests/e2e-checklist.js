const assert = require("node:assert/strict");
const { openTestApp } = require("./e2e-helper");

(async () => {
  const { browser, page, errors } = await openTestApp();
  try {
    const repaired = await page.evaluate(() => {
      const holder = document.createElement("div");
      holder.append(richMarkdownFragment("- [ ] \nОсиротілий текст"));
      return { markdown: richSerialize(holder), paragraphs: holder.querySelectorAll("p").length };
    });
    assert.deepEqual(repaired, { markdown: "- [ ] Осиротілий текст", paragraphs: 0 });
    await page.locator("#add-task-btn").click();
    await page.locator("#task-title").fill("Перевірити чекліст");
    await page.locator("#task-editor-back").click();
    const card = page.locator(".swipe-row").filter({ hasText: "Перевірити чекліст" }).first();
    await card.waitFor({ state: "visible" });
    await card.locator(".task-open").click();
    await page.locator("#task-actions-trigger").click();
    await page.locator("#task-add-checklist").click();
    await page.locator("#task-description .rich-checklist input").waitFor();
    await page.locator("#task-description .rich-checklist li").first().click();
    await page.locator("#task-editor.description-edit-mode").waitFor();
    await page.keyboard.type("Перший пункт");
    await page.keyboard.press("Enter");
    assert.equal(await page.locator("#task-description").evaluate(() => {
      const selection = getSelection();
      const anchor = selection.anchorNode;
      const element = anchor.nodeType === Node.ELEMENT_NODE ? anchor : anchor.parentElement;
      return element.closest(".checklist-item-text") === document.querySelector("#task-description .rich-checklist li:last-child .checklist-item-text");
    }), true);
    await page.keyboard.type("Другий пункт");
    await page.locator("#task-description .rich-checklist input").first().check();
    await page.locator("#description-edit-save").click();
    await page.locator("#task-editor-back").click();
    await card.locator(".task-checklist-count").waitFor({ state: "visible" });
    assert.equal(await card.locator(".task-checklist-count").textContent(), "1/2");
    assert.equal(await card.locator(".task-description-preview").isVisible(), false,
      await card.locator(".task-description-preview").textContent());
    await page.reload();
    const restored = page.locator(".swipe-row").filter({ hasText: "Перевірити чекліст" }).first();
    await restored.waitFor({ state: "visible" });
    assert.equal(await restored.locator(".task-checklist-count").textContent(), "1/2");
    const stored = await page.evaluate(async () => (await taskDb.all()).find(task => task.title === "Перевірити чекліст").description);
    assert.match(stored, /- \[x\] Перший пункт\n- \[ \] Другий пункт/);
    await restored.locator(".task-open").click();
    assert.equal(await page.locator("#task-description .rich-checklist input:checked").count(), 1);
    assert.equal(await page.locator("#task-description .rich-checklist li").count(), 2);
    assert.equal(await page.locator("#task-description").evaluate(el => getComputedStyle(el).maxHeight), "none");
    await page.locator("#task-description").click();
    await page.keyboard.type("Тимчасовий текст");
    assert.match(await page.locator("#task-description").innerText(), /Тимчасовий текст/);
    await page.locator("#description-edit-overlay").click({ position: { x: 5, y: 5 } });
    await page.locator("#description-save-confirm").waitFor({ state: "visible" });
    await page.locator("#description-save-no").click();
    assert.equal(await page.locator("#task-description .rich-checklist li").count(), 2);
    assert.doesNotMatch(await page.locator("#task-description").innerText(), /Тимчасовий текст/);
    await page.locator("#task-editor-back").click();
    assert.equal(await restored.locator(".task-checklist-count").textContent(), "1/2");
    await restored.locator(".task-open").click();
    const firstTextBox = await page.locator("#task-description .rich-checklist li").first().locator(".checklist-item-text").boundingBox();
    await page.mouse.move(firstTextBox.x + 25, firstTextBox.y + firstTextBox.height / 2);
    await page.mouse.down();
    await page.locator("#task-description .checklist-drag-source").waitFor({ state: "attached" });
    assert.equal(await page.locator("#task-editor").evaluate(el => el.classList.contains("description-edit-mode")), false);
    const secondBox = await page.locator("#task-description .rich-checklist li").nth(1).boundingBox();
    await page.mouse.move(firstTextBox.x + 25, secondBox.y + secondBox.height - 2, { steps: 5 });
    await page.mouse.up();
    await page.locator(".checklist-drag-preview").waitFor({ state: "detached" });
    assert.match(await page.locator("#task-description .rich-checklist li").first().innerText(), /Другий пункт/);
    await page.locator("#task-editor-back").click();
    await page.reload();
    const reordered = await page.evaluate(async () => (await taskDb.all()).find(task => task.title === "Перевірити чекліст").description);
    assert.match(reordered, /- \[ \] Другий пункт\n- \[x\] Перший пункт/);
    await page.locator(".swipe-row").filter({ hasText: "Перевірити чекліст" }).first().locator(".task-open").click();
    const swipeItem = page.locator("#task-description .rich-checklist li").first();
    const textBox = await swipeItem.locator(".checklist-item-text").boundingBox();
    const swipeY = textBox.y + textBox.height / 2;
    await page.mouse.move(textBox.x + 75, swipeY);
    await page.mouse.down();
    await page.mouse.move(textBox.x + 40, swipeY, { steps: 4 });
    await page.mouse.up();
    await page.locator("#task-description .checklist-swiping").waitFor({ state: "detached" });
    assert.equal(await page.locator("#task-description .rich-checklist li").count(), 2);
    assert.equal(await page.locator("#task-editor").evaluate(el => el.classList.contains("description-edit-mode")), false);
    await page.mouse.move(textBox.x + 75, swipeY);
    await page.mouse.down();
    await page.mouse.move(textBox.x - 20, swipeY, { steps: 6 });
    await page.mouse.up();
    await page.waitForFunction(() => document.querySelectorAll("#task-description .rich-checklist li").length === 1);
    assert.equal(await page.locator("#task-description .rich-checklist li").count(), 1);
    assert.equal(await page.locator("#task-editor").evaluate(el => el.classList.contains("description-edit-mode")), false);
    await page.locator("#task-editor-back").click();
    await page.locator("#task-editor").waitFor({ state: "hidden" });
    await page.reload();
    const deleted = await page.evaluate(async () => (await taskDb.all()).find(task => task.title === "Перевірити чекліст").description);
    assert.equal(deleted, "- [x] Перший пункт");
    await page.locator(".swipe-row").filter({ hasText: "Перевірити чекліст" }).first().locator(".task-open").click();
    await page.locator("#task-description .checklist-item-text").click();
    await page.locator("#task-editor.description-edit-mode").waitFor();
    await page.keyboard.press("End");
    await page.keyboard.press("Enter");
    await page.keyboard.type("Новий пункт");
    assert.equal(await page.locator("#task-description .rich-checklist li").count(), 2);
    const newHandle = await page.locator("#task-description .rich-checklist li").nth(1).locator(".checklist-drag-handle").boundingBox();
    const oldItem = await page.locator("#task-description .rich-checklist li").first().boundingBox();
    await page.mouse.move(newHandle.x + newHandle.width / 2, newHandle.y + newHandle.height / 2);
    await page.mouse.down();
    await page.locator("#task-description .checklist-drag-source").waitFor({ state: "attached" });
    await page.mouse.move(newHandle.x + newHandle.width / 2, oldItem.y + 2, { steps: 5 });
    await page.mouse.up();
    await page.locator(".checklist-drag-preview").waitFor({ state: "detached" });
    assert.match(await page.locator("#task-description .rich-checklist li").first().innerText(), /Новий пункт/);
    assert.equal(await page.locator("#task-editor").evaluate(el => el.classList.contains("description-edit-mode")), true);
    const modalText = await page.locator("#task-description .rich-checklist li").first().locator(".checklist-item-text").boundingBox();
    await page.mouse.move(modalText.x + 75, modalText.y + modalText.height / 2);
    await page.mouse.down();
    await page.mouse.move(modalText.x - 20, modalText.y + modalText.height / 2, { steps: 6 });
    await page.mouse.up();
    await page.waitForFunction(() => document.querySelectorAll("#task-description .rich-checklist li").length === 1);
    assert.equal(await page.locator("#task-editor").evaluate(el => el.classList.contains("description-edit-mode")), true);
    await page.locator("#description-edit-save").click();
    await page.locator("#task-editor-back").click();
    await page.locator("#task-editor").waitFor({ state: "hidden" });
    await page.reload();
    const modalDeleted = await page.evaluate(async () => (await taskDb.all()).find(task => task.title === "Перевірити чекліст").description);
    assert.equal(modalDeleted, "- [x] Перший пункт");
    assert.deepEqual(errors, []);
    console.log("Checklist scenario passed");
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
